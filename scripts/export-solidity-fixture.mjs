import {readFileSync,writeFileSync} from 'node:fs';
import {build,nonmember} from '../src/core.mjs';
import {verifyNonMembership} from '../src/verify.mjs';

const tree=build(JSON.parse(readFileSync(new URL('../data/epoch-1.json',import.meta.url))));
const proof=nonmember(tree,'0x0000000000000000000000000000000000000006');
if(!verifyNonMembership(proof,{...tree.context,root:tree.root}))throw Error('fixture verification failed');
const member=(side,p)=>[
 `        p.${side}.account = ${p.address};`,
 `        p.${side}.index = ${p.index};`,
 `        p.${side}.siblings = new bytes32[](${p.siblings.length});`,
 ...p.siblings.map((s,i)=>`        p.${side}.siblings[${i}] = ${s};`)
].join('\n');
const source=`// SPDX-License-Identifier: MIT
// Generated by node scripts/export-solidity-fixture.mjs from pinned epoch-1.json.
pragma solidity ^0.8.24;
import "../contracts/ListProof.sol";
library GeneratedProofFixture {
    function middle() internal pure returns (ListProofVerifier.NonMember memory p) {
        p.epoch = ${proof.context.epoch};
        p.root = ${proof.root};
        p.count = ${proof.count};
        p.target = ${proof.target};
        p.hasLeft = true;
        p.hasRight = true;
${member('left',proof.left)}
${member('right',proof.right)}
    }
}
`;
const target=new URL('../test-solidity/GeneratedProofFixture.sol',import.meta.url);
if(process.argv.includes('--check')){
 if(readFileSync(target,'utf8')!==source)throw Error('Solidity fixture is stale');
 console.log('Generated Solidity fixture matches pinned JavaScript proof');
}else{
 writeFileSync(target,source);
 console.log(`Wrote ${target.pathname}`);
}
